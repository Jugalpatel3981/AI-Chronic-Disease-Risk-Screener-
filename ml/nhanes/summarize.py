"""Write a Markdown summary of the processed NHANES dataset to docs/data/.

Usage (after build_dataset):
    python -m ml.nhanes.summarize
"""

import sys

import numpy as np
import pandas as pd

from .config import PROCESSED_DIR, REPO_ROOT

LABELS = {
    "label_hypertension": "Hypertension (≥130/80 mmHg or on medication)",
    "label_hypertension_stage2": "Hypertension stage 2 (≥140/90 or on medication)",
    "label_diabetes": "Diabetes (HbA1c ≥6.5%, diagnosed, or treated)",
    "label_prediabetes": "Prediabetes (HbA1c 5.7–6.4% or told prediabetes)",
    "label_ckd": "CKD (eGFR <60 or urine ACR ≥30 mg/g)",
}

FEATURES = {
    "age": "Age (years, 80 = 80+)",
    "sex_male": "Sex (1 = male)",
    "height_cm": "Height (cm)",
    "weight_kg": "Weight (kg)",
    "bmi": "BMI (kg/m²)",
    "waist_cm": "Waist circumference (cm)",
    "exercise_min_week": "Leisure exercise (min/week)",
    "sedentary_min_day": "Sitting time (min/day)",
    "sleep_hours": "Sleep (hours/night)",
    "alcohol_drinks_week": "Alcohol (drinks/week)",
    "smoking_status": "Smoking (0 never, 1 former, 2 current)",
    "calories_kcal": "Energy intake (kcal/day, 24-h recall)",
    "family_history_diabetes": "Family history of diabetes (not asked in 2021–2023)",
}


def weighted_pct(g: pd.DataFrame, col: str) -> float:
    m = g[col].notna() & (g["survey_weight"] > 0)
    return float(np.average(g.loc[m, col], weights=g.loc[m, "survey_weight"]) * 100)


def main() -> int:
    df = pd.read_parquet(PROCESSED_DIR / "nhanes_adults.parquet")
    lines = [
        "# NHANES adult dataset summary",
        "",
        "Generated by `python -m ml.nhanes.summarize`. Source: CDC National Health and "
        "Nutrition Examination Survey (NHANES), public-use files.",
        "",
        f"- **Participants:** {len(df):,} examined, non-pregnant adults aged 18+",
        f"- **Training cycles (2011–2018):** {(df.split == 'train').sum():,} people",
        f"- **Temporal test cycle (2021–2023):** {(df.split == 'temporal_test').sum():,} people "
        "(never used for training)",
        "",
        "## Prevalence by survey cycle",
        "",
        "Percentages are survey-weighted, so they estimate the US adult population.",
        "",
    ]
    header = "| Cycle | n | " + " | ".join(LABELS.values()) + " |"
    lines += [header, "|" + "---|" * (len(LABELS) + 2)]
    for cycle, g in df.groupby("cycle"):
        vals = " | ".join(f"{weighted_pct(g, c):.1f}%" for c in LABELS)
        lines.append(f"| {cycle} | {len(g):,} | {vals} |")

    lines += ["", "## Features", "", "| Feature | Median | Missing |", "|---|---|---|"]
    for col, name in FEATURES.items():
        lines.append(f"| {name} | {df[col].median():.1f} | {df[col].isna().mean() * 100:.1f}% |")

    lines += [
        "",
        "## Notes",
        "",
        "- Lifestyle values are self-reported per person; body measures and labs are measured "
        "by NHANES staff.",
        "- Blood pressure was measured by auscultation up to 2017–2018 and by an oscillometric "
        "device in 2021–2023. That change is part of what the temporal test checks.",
        "- Labels use one visit's measurements, as is standard for NHANES prevalence estimates. "
        "A clinical diagnosis would need repeat measurements.",
    ]

    out = REPO_ROOT / "docs" / "data" / "nhanes_dataset.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[summary] wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
